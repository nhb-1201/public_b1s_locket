#!/usr/bin/env node
/**
 * B1sTeam — Build tool cho MITM scripts + Shadowrocket module.
 *
 *   node ios/build.mjs           # build: src → scripts/*.js + locketgold.sgmodule
 *   node ios/build.mjs --check   # chỉ kiểm tra (exit 1 nếu output cũ hơn source)
 *
 * Quy trình:
 *   1. ios/src/lib/*.js   — thư viện dùng chung (được inline, KHÔNG chạy độc lập)
 *   2. ios/src/*.src.js   — mã nguồn từng script, dùng `// @b1s-include <path>` để nhúng
 *   3. ios/scripts/*.js   — OUTPUT (file thật script Shadowrocket tải) — commit lại
 *   4. ios/locketgold.sgmodule — sinh từ ios/alfretro-allinone.conf (MITM %APPEND% cho module)
 *
 * Shadowrocket KHÔNG hỗ trợ require/import giữa các file — mọi script phải self-contained,
 * nên thư viện dùng chung được INLINE thẳng lúc build (1 nguồn chân lý, không copy-paste).
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = dirname(fileURLToPath(import.meta.url));

/* Version (nguon su that duy nhat: version.json o thu muc goc repo) */
const VERSION_JSON = join(ROOT, "..", "version.json");
let VERSION = { version: "0.0.0", updated: "unknown", channel: "dev", product: "LocketGold" };
try {
  VERSION = JSON.parse(readFileSync(VERSION_JSON, "utf8"));
} catch (e) {
  console.error("Khong doc duoc version.json:", e.message);
}
const BUILD_AT = new Date().toISOString().replace(".000Z", "Z");
const VERSION_BLOCK =
  `/* B1sTeam — ${VERSION.product} v${VERSION.version} · cap nhat ${VERSION.updated} · build ${BUILD_AT} */\n`
  + `var B1S_VERSION = "${VERSION.version}";\n`
  + `var B1S_UPDATED = "${VERSION.updated}";\n`
  + `var B1S_BUILD = "${BUILD_AT}";\n`;

const SRC = join(ROOT, "src");
const LIB = join(SRC, "lib");
const OUT = join(ROOT, "scripts");
const REPO_IOS = ROOT;

const args = process.argv.slice(2);
const CHECK = args.includes("--check");

const AUTHOR = "// author: B1sTeam | b1s.id.vn | @b1steam | github.com/nhb-1201/public_b1s_locket\n";
const STAMP = "// ⚠ GENERATED by ios/build.mjs — ĐỪNG SỬA TRỰC TIẾP. Sửa ios/src/*.src.js hoặc ios/src/lib/*.js rồi chạy `node ios/build.mjs`.\n";

/** Inline mọi dòng `// @b1s-include <path>` (đệ quy, chống vòng lặp). */
function inline(filePath, seen = new Set(), depth = 0) {
  if (depth > 8) throw new Error("@b1s-include sâu quá 8 cấp: " + filePath);
  if (seen.has(filePath)) throw new Error("@b1s-include vòng lặp tại " + filePath);
  seen.add(filePath);
  const dir = dirname(filePath);
  const raw = readFileSync(filePath, "utf8");
  const out = [];
  for (const line of raw.split("\n")) {
    const m = /^\s*\/\/\s*@b1s-include\s+(\S+)\s*$/.exec(line);
    if (!m) { out.push(line); continue; }
    const target = resolve(dir, m[1]);
    out.push(`/* ─── BEGIN inlined: ${relative(SRC, target)} ─── */`);
    out.push(inline(target, seen, depth + 1));
    out.push(`/* ─── END inlined: ${relative(SRC, target)} ─── */`);
  }
  return out.join("\n");
}

function buildScripts() {
  mkdirSync(OUT, { recursive: true });
  const srcFiles = readdirSync(SRC).filter((f) => f.endsWith(".src.js"));
  const results = [];
  for (const file of srcFiles) {
    const name = file.replace(/\.src\.js$/, ".js");
    const source = join(SRC, file);
    const target = join(OUT, name);
    const body = inline(source).replace(/\r\n/g, "\n");
    // Nếu source đã có dòng author thì giữ nguyên — ngược lại thêm.
    // Chen hang version + banner ngay sau dong author (neu co) de log tren may luon biet version.
    let out = body;
    const authorIdx = out.indexOf(AUTHOR.trim());
    if (authorIdx === 0) {
      const afterAuthor = authorIdx + AUTHOR.trim().length;
      out = out.slice(0, afterAuthor) + "\n" + VERSION_BLOCK + out.slice(afterAuthor);
    } else {
      out = VERSION_BLOCK + out;
    }
    const content = STAMP + out;
    results.push({ source, target, content });
  }
  return results;
}

/** Sinh Shadowrocket MODULE (.sgmodule) từ .conf — 1 nguồn, không bao giờ lệch nhau. */
function buildModule() {
  const confPath = join(REPO_IOS, "alfretro-allinone.conf");
  const conf = readFileSync(confPath, "utf8").replace(/\r\n/g, "\n");
  // Dong bo version: .conf phai khai #!version khop version.json
  const confVer = (conf.match(/^#!version=(.+)$/m) || [])[1];
  if (!confVer) {
    console.error("STALE  .conf thieu dong #!version= — them #!version=" + VERSION.version + " vao alfretro-allinone.conf");
    process.exit(1);
  }
  if (conf.includes("$1") || /\.js\$\d/.test(conf)) {
    console.error("STALE  .conf có script-path hỏng (ký tự '$1' hoặc .js$version) — sửa lại URL script-path");
    process.exit(1);
  }
  const noV = [...conf.matchAll(/script-path=([^\s,]+)/g)].filter((m) => !m[1].includes("?v="));
  if (noV.length) {
    console.error("STALE  " + noV.length + " script-path thiếu ?v=" + VERSION.version + " (cache-bust) — sửa lại .conf");
    process.exit(1);
  }
  const badV = [...conf.matchAll(/\?v=([0-9]+\.[0-9]+\.[0-9]+)/g)].filter((m) => m[1] !== String(VERSION.version));
  if (badV.length) {
    console.error("STALE  .conf có ?v= không khớp version.json (" + [...new Set(badV.map((m) => m[1]))].join(", ") + ") — cần ?v=" + VERSION.version);
    process.exit(1);
  }
  if (confVer.trim() !== String(VERSION.version)) {
    console.error("STALE  .conf dang #!version=" + confVer.trim() + " nhung version.json la " + VERSION.version + " — cap nhat ca hai");
    process.exit(1);
  }
  const moduleBody = conf
    .replace("#!name=B1sTeam — AlFreToU · All-In-One (.conf)", "#!name=B1sTeam — AlFreToU · All-In-One (.module)")
    .replace(/\[MITM\]\nhostname = /, "[MITM]\nhostname = %APPEND%, ")
    .replace(/#!desc=([^\n]*)/, (m) => m.replace(".conf", ".module"));
  const content =
    "# ⚠ GENERATED by ios/build.mjs từ ios/alfretro-allinone.conf — ĐỪNG SỬA TRỰC TIẾP.\n" +
    "# Shadowrocket .module: MITM dùng %APPEND% để gộp hostname với config hiện có.\n" +
    moduleBody;
  return { source: confPath, target: join(REPO_IOS, "locketgold.sgmodule"), content };
}

const outputs = [...buildScripts(), buildModule()];
console.log(`BUILD  ${VERSION.product} v${VERSION.version} · cap nhat ${VERSION.updated} · ${BUILD_AT}`);
let stale = 0;
for (const { source, target, content } of outputs) {
  let current = null;
  try { current = readFileSync(target, "utf8"); } catch { /* chưa có */ }
  const same = current === content;
  if (CHECK) {
    if (!same) { console.error(`STALE  ${relative(REPO_IOS, target)}  (source: ${relative(REPO_IOS, source)})`); stale++; }
    else console.log(`OK     ${relative(REPO_IOS, target)}`);
  } else {
    writeFileSync(target, content, "utf8");
    // Self-check chỉ cho .js (bỏ qua .sgmodule — file INI, không phải JS).
    // Bọc trong function wrapper — Shadowrocket cho phép `return` ở top-level script.
    if (target.endsWith(".js")) {
      try {
        new vm.Script("(function(){\n" + content + "\n});", { filename: relative(REPO_IOS, target) });
      } catch (e) {
        console.error(`SYNTAX FAIL  ${relative(REPO_IOS, target)} — ${e.message}`);
        process.exit(1);
      }
    }
    console.log(`${same ? "UNCHANGED" : "WROTE"}  ${relative(REPO_IOS, target)}  (${(content.length / 1024).toFixed(1)} KB)`);
  }
}
if (CHECK && stale) { console.error(`\n${stale} file chưa build — chạy: node ios/build.mjs`); process.exit(1); }
